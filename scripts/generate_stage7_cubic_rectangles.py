#!/usr/bin/env python3
"""Generate signed cubic rectangle arithmetic from the existing rational tables.

Python selects outward rounded batch totals. Lean rechecks every inequality.
This target does not yet bound the tail or assert signs of the full cubic.
"""
import argparse
from fractions import Fraction
from pathlib import Path
import re

POINTS = {90: (Fraction(-26, 100), Fraction(-23, 100)),
          55: (Fraction(6, 1000), Fraction(18, 1000)),
          42: (Fraction(-19, 1000), Fraction(-9, 1000)),
          15: (Fraction(127, 1000), Fraction(134, 1000))}


def table(source, name):
    block = source.split(f'def {name} (j : ℕ) : ℝ :=', 1)[1].split('| _ => 0', 1)[0]
    rows = re.findall(r'\| (\d+) => \((-?\d+) / (\d+) : ℝ\)', block)
    if [int(j) for j, _, _ in rows] != list(range(20)):
        raise ValueError(f'Expected twenty ordered rational entries: {name}')
    return [Fraction(int(n), int(d)) for _, n, d in rows]


def rat(x):
    return f'({x.numerator} / {x.denominator} : ℝ)'


def generate(point, kernel_dir, weight_dir, output_dir):
    pre = f'hpThetaJensenCubicNeg{point}'
    rounded = [[], []]
    rectangles = [[], []]
    totals = [Fraction(0), Fraction(0)]
    actual = [Fraction(0), Fraction(0)]
    proofs, prefixes = [], []
    for side, label in enumerate(('Lower', 'Upper')):
        prefixes.append(f'''\ntheorem {pre}{label}Prefix000 :
    (∑ b ∈ Finset.range 0, {pre}Batch{label} b) = (0 : ℝ) := by
  simp
''')
    for b in range(80):
        k = f'hpThetaJensenCellsBatch{b:03}'
        w = f'hpThetaJensenCubicWeightBatch{b:03}Neg{point}'
        ks = (kernel_dir / f'Stage5ThetaJensenCellsBatch{b:03}.lean').read_text(encoding='utf-8')
        ws = (weight_dir / f'Stage7ThetaJensenCubicWeightBatch{b:03}.lean').read_text(encoding='utf-8')
        kl, ku = table(ks, k+'Lower'), table(ks, k+'Upper')
        wl, wu = table(ws, w+'Lower'), table(ws, w+'Upper')
        if not all(0 <= l <= u for l, u in zip(kl, ku)):
            raise ValueError('Kernel endpoints must be ordered and nonnegative')
        if not all(l <= u for l, u in zip(wl, wu)):
            raise ValueError('Weight endpoints must be ordered')
        vals = [sum((min(l*a, u*a)/1600 for l,u,a in zip(kl,ku,wl)),Fraction(0)),
                sum((max(l*a, u*a)/1600 for l,u,a in zip(kl,ku,wu)),Fraction(0))]
        for side, label in enumerate(('Lower', 'Upper')):
            scaled = vals[side]*10**15
            n = scaled.numerator//scaled.denominator
            if side and scaled.denominator != 1:
                n += 1
            bound = Fraction(n, 10**15)
            if not (bound <= vals[side] if side==0 else vals[side] <= bound):
                raise ValueError('Outward rounding failed')
            rounded[side].append(f'  | {b} => {rat(bound)}')
            op = 'min' if side==0 else 'max'
            rectangles[side].append(f'''  | {b} => ∑ j ∈ Finset.range 20,
      {op} ({k}Lower j * {w}{label} j)
        ({k}Upper j * {w}{label} j) / 1600''')
            totals[side] += bound
            actual[side] += vals[side]
            prefixes.append(f'''\ntheorem {pre}{label}Prefix{b+1:03} :
    (∑ b ∈ Finset.range {b+1}, {pre}Batch{label} b) = {rat(totals[side])} := by
  change (∑ b ∈ Finset.range ({b} + 1), {pre}Batch{label} b) = _
  rw [Finset.sum_range_succ, {pre}{label}Prefix{b:03}]
  norm_num [{pre}Batch{label}]
''')
        proofs.append(f'''\ntheorem {pre}RectanglesBatch{b:03}_bounds :
    {pre}BatchLower {b} ≤ {pre}RectangleLower {b} ∧
      {pre}RectangleUpper {b} ≤ {pre}BatchUpper {b} := by
  norm_num [{pre}BatchLower, {pre}BatchUpper,
    {pre}RectangleLower, {pre}RectangleUpper, min_def, max_def,
    Finset.sum_range_succ, {k}Lower, {k}Upper, {w}Lower, {w}Upper]
''')
    lower, upper = POINTS[point]
    if not lower <= totals[0] <= actual[0] <= actual[1] <= totals[1] <= upper:
        raise ValueError(f'Global enclosure does not hold for point {-point}')
    header = '''/-
Copyright (c) 2026 Adil Fagiri. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Adil Fagiri
-/
import HodgeProofHP.Stage5ThetaJensenAllCellCertificates
import HodgeProofHP.Stage7ThetaJensenCubicWeightAllBatches
import Mathlib.Tactic

/-! Generated by scripts/generate_stage7_cubic_rectangles.py.
Exact signed rectangle sums only. Full integrals and tails are separate.
No evaluation sign or cubic hyperbolicity is asserted here. -/
noncomputable section
open scoped BigOperators
namespace HodgeProofHP
'''
    defs = []
    for names, rows in ((('BatchLower','BatchUpper'),rounded),
                        (('RectangleLower','RectangleUpper'),rectangles)):
        for name, entries in zip(names,rows):
            defs.append(f'\ndef {pre}{name} (b : ℕ) : ℝ :=\n  match b with\n' +
                        '\n'.join(entries) + '\n  | _ => 0\n')
    cases = '\n'.join(f'  · exact {pre}RectanglesBatch{b:03}_bounds' for b in range(80))
    footer = f'''
theorem {pre}_rectangleBatch_bounds (b : Fin 80) :
    {pre}BatchLower b.val ≤ {pre}RectangleLower b.val ∧
      {pre}RectangleUpper b.val ≤ {pre}BatchUpper b.val := by
  fin_cases b
{cases}

theorem {pre}_rectangle_lower_numeric :
    {rat(lower)} ≤ ∑ b ∈ Finset.range 80, {pre}RectangleLower b := by
  have h : (∑ b ∈ Finset.range 80, {pre}BatchLower b) ≤
      ∑ b ∈ Finset.range 80, {pre}RectangleLower b := by
    apply Finset.sum_le_sum
    intro b hb
    exact ({pre}_rectangleBatch_bounds ⟨b, Finset.mem_range.mp hb⟩).1
  have hn : {rat(lower)} ≤ ∑ b ∈ Finset.range 80, {pre}BatchLower b := by
    rw [{pre}LowerPrefix080]
    norm_num
  exact le_trans hn h

theorem {pre}_rectangle_upper_numeric :
    (∑ b ∈ Finset.range 80, {pre}RectangleUpper b) ≤ {rat(upper)} := by
  have h : (∑ b ∈ Finset.range 80, {pre}RectangleUpper b) ≤
      ∑ b ∈ Finset.range 80, {pre}BatchUpper b := by
    apply Finset.sum_le_sum
    intro b hb
    exact ({pre}_rectangleBatch_bounds ⟨b, Finset.mem_range.mp hb⟩).2
  have hn : (∑ b ∈ Finset.range 80, {pre}BatchUpper b) ≤ {rat(upper)} := by
    rw [{pre}UpperPrefix080]
    norm_num
  exact le_trans h hn

#print axioms {pre}_rectangleBatch_bounds
#print axioms {pre}_rectangle_lower_numeric
#print axioms {pre}_rectangle_upper_numeric
end HodgeProofHP
'''
    output_dir.mkdir(parents=True, exist_ok=True)
    output = output_dir/f'Stage7ThetaJensenCubicRectanglesNeg{point}.lean'
    output.write_text(header+''.join(defs+proofs+prefixes)+footer,encoding='utf-8')
    print(f'{output}: exact rational total enclosure [{float(totals[0]):.12f}, {float(totals[1]):.12f}]')


if __name__ == '__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--point',type=int,choices=list(POINTS))
    ap.add_argument('--kernel-dir',type=Path,default=Path('HodgeProofHP'))
    ap.add_argument('--weight-dir',type=Path,default=Path('HodgeProofHP'))
    ap.add_argument('--output-dir',type=Path,default=Path('HodgeProofHP'))
    args=ap.parse_args()
    for point in ([args.point] if args.point else POINTS):
        generate(point,args.kernel_dir,args.weight_dir,args.output_dir)
