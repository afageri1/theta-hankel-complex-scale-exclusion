#!/usr/bin/env python3
"""Instantiate signed integration using all existing kernel and weight batches."""
import argparse
from pathlib import Path


def generate(point, output):
    if point not in (90, 55, 42, 15):
        raise ValueError('Point must be one of 90, 55, 42, 15 (its negative is used)')
    chunks = ['''/-
Copyright (c) 2026 Adil Fagiri. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Adil Fagiri
-/
import HodgeProofHP.Stage7ThetaJensenCubicIntegralPartition
import HodgeProofHP.Stage5ThetaJensenAllCellCertificates
import HodgeProofHP.Stage7ThetaJensenCubicWeightAllBatches

/-! Generated by scripts/generate_stage7_cubic_batch_integrals.py.
Each actual batch integral is bounded by its signed rational rectangles.
The finite numerical sums and the tail still require separate certificates. -/
noncomputable section
open MeasureTheory
open scoped BigOperators
namespace HodgeProofHP
''']
    reports = []
    for b in range(80):
        kernel = f'hpThetaJensenCellsBatch{b:03}'
        weight = f'hpThetaJensenCubicWeightBatch{b:03}Neg{point}'
        name = f'hpThetaJensenCubicBatch{b:03}Neg{point}_integral_bounds'
        chunks.append(f'''
theorem {name} :
    (∑ j ∈ Finset.range 20,
      min ({kernel}Lower j * {weight}Lower j)
        ({kernel}Upper j * {weight}Lower j) / 1600) ≤
      (∫ u : ℝ in Set.Ioo ({b} / 80 : ℝ) (({b} + 1) / 80 : ℝ),
        hpRiemannThetaDifferentialKernel u * hpThetaJensenCubicWeight (-{point}) u) ∧
    (∫ u : ℝ in Set.Ioo ({b} / 80 : ℝ) (({b} + 1) / 80 : ℝ),
      hpRiemannThetaDifferentialKernel u * hpThetaJensenCubicWeight (-{point}) u) ≤
      ∑ j ∈ Finset.range 20,
        max ({kernel}Lower j * {weight}Upper j)
          ({kernel}Upper j * {weight}Upper j) /
          1600 := by
  have h := hpThetaJensenCubic_batchIntegral_of_bounds (-{point}) ({20*b} : ℝ)
    (by norm_num) {kernel}Lower {kernel}Upper
    {weight}Lower {weight}Upper
    {kernel}_bounds {weight}_bounds
  simpa only [show ({20*b} : ℝ) / 1600 = {b} / 80 by norm_num,
    show (({20*b} : ℝ) + 20) / 1600 = ({b} + 1) / 80 by norm_num] using h
''')
        reports.append(name)
    chunks.extend(f'\n#print axioms {name}\n' for name in reports)
    chunks.append('end HodgeProofHP\n')
    output.write_text(''.join(chunks), encoding='utf-8')
    print(f'Wrote {output}: 80 batch integral bounds')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--point', type=int, required=True)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    output = args.output or Path(
        f'HodgeProofHP/Stage7ThetaJensenCubicBatchIntegralsNeg{args.point}.lean')
    generate(args.point, output)
