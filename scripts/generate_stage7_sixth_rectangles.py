#!/usr/bin/env python3
"""Generate exact sixth-order rectangle sums from unchanged Stage 5 tables.

Run from the repository root. Python only chooses rounded bounds; the
generated Lean file verifies each sum with norm_num, without native_decide.
"""
import argparse
from fractions import Fraction
from pathlib import Path
import re


def table(source, name):
    block = source.split(f"def {name} (j : ℕ) : ℝ :=", 1)[1].split("| _ => 0", 1)[0]
    rows = re.findall(r"\| (\d+) => \((\d+) / (\d+) : ℝ\)", block)
    if [int(j) for j, _, _ in rows] != list(range(20)):
        raise ValueError(f"Expected exactly 20 ordered rational entries in {name}")
    return [Fraction(int(a), int(b)) for _, a, b in rows]


def rational(x):
    return f"({x.numerator} / {x.denominator} : ℝ)"


def generate(root, output):
    scale = 10**15
    totals = [Fraction(0), Fraction(0)]
    exact_totals = [Fraction(0), Fraction(0)]
    rounded = [[], []]
    prefix_proofs = []
    rectangles = [[], []]
    proofs = []
    for b in range(80):
        stem = f"hpThetaJensenCellsBatch{b:03}"
        source = (root / "HodgeProofHP" / f"Stage5ThetaJensenCellsBatch{b:03}.lean").read_text(encoding="utf-8")
        for side, label in enumerate(("Lower", "Upper")):
            xs = table(source, stem + label)
            value = sum((Fraction(20*b+j+side, 1600)**6*x/1600
                         for j, x in enumerate(xs)), Fraction(0))
            scaled = value * scale
            numerator = scaled.numerator // scaled.denominator
            if side and scaled.denominator != 1:
                numerator += 1
            bound = Fraction(numerator, scale)
            assert (bound <= value) if side == 0 else (value <= bound)
            rounded[side].append(f"  | {b} => {rational(bound)}")
            rectangles[side].append(
                f"  | {b} => ∑ j ∈ Finset.range 20,\n"
                f"      ((({20*b} : ℝ) + (j : ℝ) + {side}) / 1600) ^ 6 *\n        "
                f"{stem}{label} j / 1600")
            totals[side] += bound
            exact_totals[side] += value
            previous = f"hpThetaJensenSixth{label}Prefix{b:03}"
            if b == 0:
                prefix_proofs.append(f"""
theorem {previous} :
    (∑ b ∈ Finset.range 0, hpThetaJensenSixthBatch{label} b) = (0 : ℝ) := by
  simp
""")
            prefix_proofs.append(f"""
theorem hpThetaJensenSixth{label}Prefix{b+1:03} :
    (∑ b ∈ Finset.range {b+1}, hpThetaJensenSixthBatch{label} b) =
      {rational(totals[side])} := by
  change (∑ b ∈ Finset.range ({b} + 1), hpThetaJensenSixthBatch{label} b) = _
  rw [Finset.sum_range_succ, {previous}]
  norm_num [hpThetaJensenSixthBatch{label}]
""")
        proofs.append(f"""
theorem hpThetaJensenSixthRectanglesBatch{b:03}_bounds :
    hpThetaJensenSixthBatchLower {b} ≤ hpThetaJensenSixthRectangleLower {b} ∧
      hpThetaJensenSixthRectangleUpper {b} ≤ hpThetaJensenSixthBatchUpper {b} := by
  norm_num [hpThetaJensenSixthBatchLower, hpThetaJensenSixthBatchUpper,
    hpThetaJensenSixthRectangleLower, hpThetaJensenSixthRectangleUpper,
    Finset.sum_range_succ, {stem}Lower, {stem}Upper]
""")
    lower = Fraction(592, 10**6)
    upper = Fraction(608, 10**6) - Fraction(1, 50000000)
    assert lower <= totals[0] <= exact_totals[0]
    assert exact_totals[1] <= totals[1] <= upper
    header = """/-
Copyright (c) 2026 Adil Fagiri. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Adil Fagiri
-/
import HodgeProofHP.Stage5ThetaJensenAllCellCertificates
import Mathlib.Tactic

/-!
# Exact sixth-order rectangle certificates

Generated by scripts/generate_stage7_sixth_rectangles.py from the existing
1600 Stage 5 kernel rectangles. All arithmetic is rechecked by Lean.
These are finite numerical sums, not yet full sixth-moment bounds.
The upper bound reserves the already proved 1/50000000 tail allowance.
-/
noncomputable section
open scoped BigOperators
namespace HodgeProofHP
"""
    definitions = []
    for names, rows in ((('BatchLower', 'BatchUpper'), rounded),
                        (('RectangleLower', 'RectangleUpper'), rectangles)):
        for name, entries in zip(names, rows):
            definitions.append(f"\ndef hpThetaJensenSixth{name} (b : ℕ) : ℝ :=\n  match b with\n" +
                               "\n".join(entries) + "\n  | _ => 0\n")
    cases = "\n".join(f"  · exact hpThetaJensenSixthRectanglesBatch{b:03}_bounds" for b in range(80))
    footer = f"""
theorem hpThetaJensen_sixthRectangleBatch_bounds (b : Fin 80) :
    hpThetaJensenSixthBatchLower b.val ≤ hpThetaJensenSixthRectangleLower b.val ∧
      hpThetaJensenSixthRectangleUpper b.val ≤ hpThetaJensenSixthBatchUpper b.val := by
  fin_cases b
{cases}

theorem hpThetaJensen_sixthRectangle_lower_numeric :
    (592 / 1000000 : ℝ) ≤
      ∑ b ∈ Finset.range 80, hpThetaJensenSixthRectangleLower b := by
  have h : (∑ b ∈ Finset.range 80, hpThetaJensenSixthBatchLower b) ≤
      ∑ b ∈ Finset.range 80, hpThetaJensenSixthRectangleLower b := by
    apply Finset.sum_le_sum
    intro b hb
    exact (hpThetaJensen_sixthRectangleBatch_bounds
      ⟨b, Finset.mem_range.mp hb⟩).1
  have hn : (592 / 1000000 : ℝ) ≤
      ∑ b ∈ Finset.range 80, hpThetaJensenSixthBatchLower b := by
    rw [hpThetaJensenSixthLowerPrefix080]
    norm_num
  exact le_trans hn h

theorem hpThetaJensen_sixthRectangle_upper_numeric :
    (∑ b ∈ Finset.range 80, hpThetaJensenSixthRectangleUpper b) ≤
      (608 / 1000000 : ℝ) - 1 / 50000000 := by
  have h : (∑ b ∈ Finset.range 80, hpThetaJensenSixthRectangleUpper b) ≤
      ∑ b ∈ Finset.range 80, hpThetaJensenSixthBatchUpper b := by
    apply Finset.sum_le_sum
    intro b hb
    exact (hpThetaJensen_sixthRectangleBatch_bounds
      ⟨b, Finset.mem_range.mp hb⟩).2
  have hn : (∑ b ∈ Finset.range 80, hpThetaJensenSixthBatchUpper b) ≤
      (608 / 1000000 : ℝ) - 1 / 50000000 := by
    rw [hpThetaJensenSixthUpperPrefix080]
    norm_num
  exact le_trans h hn

#print axioms hpThetaJensen_sixthRectangleBatch_bounds
#print axioms hpThetaJensen_sixthRectangle_lower_numeric
#print axioms hpThetaJensen_sixthRectangle_upper_numeric
end HodgeProofHP
"""
    output.write_text(header + ''.join(definitions) + ''.join(proofs) +
                      ''.join(prefix_proofs) + footer, encoding='utf-8')
    for side, label in enumerate(('lower', 'upper')):
        print(f"{label}: exact={exact_totals[side]}, rounded={totals[side]}")
    print(f"Wrote {output}")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path('.'))
    parser.add_argument('--output', type=Path,
                        default=Path('HodgeProofHP/Stage7ThetaJensenSixthMomentRectangles.lean'))
    args = parser.parse_args()
    generate(args.root, args.output)
