#!/usr/bin/env python3
"""Generate one batch of 20 exact cubic-weight cell certificates.

Run from the repository root. Bounds are rounded outwards to 10^-12;
Lean checks all seven Bernstein coefficients on each cell.
"""
import argparse
from fractions import Fraction as F
from math import comb
from pathlib import Path


def coefficients(p, a, h):
    result = []
    for k in range(7):
        choose = lambda j: comb(k, j) if j <= k else 0
        b2 = a*a + F(k, 3)*a*h + F(choose(2), 15)*h*h
        b4 = (a**4 + F(2*k, 3)*a**3*h + F(2*choose(2), 5)*a*a*h*h
              + F(choose(3), 5)*a*h**3 + F(choose(4), 15)*h**4)
        b6 = (a**6 + k*a**5*h + choose(2)*a**4*h*h
              + choose(3)*a**3*h**3 + choose(4)*a*a*h**4
              + choose(5)*a*h**5 + choose(6)*h**6)
        result.append(1 + F(3*p, 2)*b2 + F(p*p, 4)*b4 + F(p**3, 120)*b6)
    return result


def rational(x):
    return f"({x.numerator} / {x.denominator} : ℝ)"


def rounded_enclosure(cs):
    scale = 10**12
    lo, hi = min(cs)*scale, max(cs)*scale
    lower = F(lo.numerator // lo.denominator, scale)
    upper = F(-(-hi.numerator // hi.denominator), scale)
    assert all(lower <= c <= upper for c in cs)
    return lower, upper


def generate(batch, output):
    if not 0 <= batch < 80:
        raise ValueError('Batch must lie between 0 and 79')
    chunks = ['''/-
Copyright (c) 2026 Adil Fagiri. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Adil Fagiri
-/
import HodgeProofHP.Stage7ThetaJensenBernsteinCoefficients

/-! Generated by scripts/generate_stage7_cubic_weight_batch.py.
Every enclosure is rechecked from seven exact Bernstein coefficients.
These are weight bounds, not integral or evaluation sign certificates. -/
noncomputable section
namespace HodgeProofHP
''']
    reports = []
    for p in (-90, -55, -42, -15):
        stem = f'hpThetaJensenCubicWeightBatch{batch:03}Neg{-p}'
        rows = [rounded_enclosure(coefficients(p, F(20*batch+j, 1600), F(1, 1600)))
                for j in range(20)]
        for side, label in enumerate(('Lower', 'Upper')):
            chunks.append(f'\ndef {stem}{label} (j : ℕ) : ℝ :=\n  match j with\n')
            chunks.extend(f'  | {j} => {rational(bounds[side])}\n'
                          for j, bounds in enumerate(rows))
            chunks.append('  | _ => 0\n')
        for j in range(20):
            i = 20*batch+j
            chunks.append(f'''
theorem {stem}Cell{j:02}_bounds (u : ℝ)
    (hu : u ∈ Set.Icc ({i} / 1600 : ℝ) ({i+1} / 1600 : ℝ)) :
    {stem}Lower {j} ≤ hpThetaJensenCubicWeight ({p}) u ∧
      hpThetaJensenCubicWeight ({p}) u ≤ {stem}Upper {j} := by
  apply hpThetaJensenCubicWeight_bounds_of_coefficients
    ({p}) ({i} / 1600) ({i+1} / 1600) u
    ({stem}Lower {j})
    ({stem}Upper {j}) (by norm_num) hu
  intro k
  fin_cases k <;>
    norm_num [hpThetaJensenCubicBernsteinCoefficient,
      hpThetaBernsteinPowerTwo, hpThetaBernsteinPowerFour,
      hpThetaBernsteinPowerSix, Nat.choose,
      {stem}Lower, {stem}Upper]
''')
        final_name = f'{stem}_bounds'
        chunks.append(f'''
theorem {final_name} (j : Fin 20) (u : ℝ)
    (hu : u ∈ Set.Icc ((({20*batch} : ℝ) + (j.val : ℝ)) / 1600)
      ((({20*batch} : ℝ) + (j.val : ℝ) + 1) / 1600)) :
    {stem}Lower j.val ≤ hpThetaJensenCubicWeight ({p}) u ∧
      hpThetaJensenCubicWeight ({p}) u ≤ {stem}Upper j.val := by
  fin_cases j
''')
        for j in range(20):
            chunks.append(f'''  · have h := {stem}Cell{j:02}_bounds u (by
      norm_num at hu ⊢
      exact hu)
    simpa using h
''')
        reports.append(final_name)
    chunks.extend(f'\n#print axioms {name}\n' for name in reports)
    chunks.append('end HodgeProofHP\n')
    output.write_text(''.join(chunks), encoding='utf-8')
    print(f'Wrote {output}: 80 cells, 560 coefficient inequalities pairs')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--batch', type=int, default=0)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    output = args.output or Path(
        f'HodgeProofHP/Stage7ThetaJensenCubicWeightBatch{args.batch:03}.lean')
    generate(args.batch, output)
