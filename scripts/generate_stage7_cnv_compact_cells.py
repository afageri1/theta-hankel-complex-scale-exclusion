def taylor(x, n):
    return sum((x**k / factorial(k) for k in range(n)), F(0))

def upper(x, n=12):
    return taylor(x, n) + x**n * F(n + 1, factorial(n) * n)

def floor_grid(x, denominator):
    return F(x.numerator * denominator // x.denominator, denominator)

def ceil_grid(x, denominator):
    return -floor_grid(-x, denominator)

def certificate(l, u):
    L = floor_grid(taylor(l/2, 12), 10**10)
    U = ceil_grid(upper(u/2), 10**10)
    a = floor_grid(F(3141592, 10**6) * L**4, 10**6)
    b = ceil_grid(F(3141593, 10**6) * U**4, 10**6)
    R = ceil_grid(16 / taylor(3*a, 32), 10**12)
    D = lambda x: 8*x**3 - 30*x**2 + 15*x
    A = lambda x: x*(16*x*x - 9*x + F(15, 2))
    B = 1 + u*(2*b-F(1, 2))
    gap = l*A(a)-D(b)-R*(16*u*b**4+B*D(b)+F(4016,125)*(1+R)*B*b**3)
    assert 0 <= l <= u <= 1 and a >= F(13,4) and 0 <= L and 0 <= U and 0 <= R
    assert L <= taylor(l/2,12) and upper(u/2) <= U
    assert a <= F(3141592,10**6)*L**4 and F(3141593,10**6)*U**4 <= b
    assert 16 <= R*taylor(3*a,32)
    return (l,u,L,U,a,b,R,gap)

def cells():
    out = []
    def split(l,u,depth=0):
        row=certificate(l,u)
        if row[-1] > 0:
            out.append(row)
        else:
            assert depth < 20, 'Subdivision depth exceeded'
            mid=(l+u)/2
            split(l,mid,depth+1)
            split(mid,u,depth+1)
    split(F(1,50),F(1))
    assert out[0][0] == F(1,50) and out[-1][1] == 1
    assert all(x[1] == y[0] for x,y in zip(out,out[1:]))
    assert all(x[-1] > 0 for x in out)
    return out

def lean(x):
    if x.denominator == 1:
        return f'({x.numerator} : ℝ)'
    return f'({x.numerator} / {x.denominator} : ℝ)'

ARITH = 'by norm_num [hpThetaTraceExpTaylorSum, Finset.sum_range_succ, Nat.factorial]'
UPPER = 'by norm_num [hpThetaTraceExpTaylorUpper, hpThetaTraceExpTaylorSum, Finset.sum_range_succ, Nat.factorial]'
GAP = 'by norm_num [hpThetaCNVBoxGap, hpThetaCNVBoxRemainder, hpThetaCNVFarLeadingPolynomial, hpThetaCNVFarDerivativePolynomial, hpThetaCNVFarTailPolynomial]'

def glue(name, groups, endpoints):
    text = f'theorem {name} (t : ℝ)\n    (ht : t ∈ Set.Icc {lean(endpoints[0][0])} {lean(endpoints[-1][1])}) :\n    0 < hpThetaCNVFarComparisonNumerator t := by\n'
    for i,g in enumerate(groups):
        lower = 'ht.1' if i == 0 else f'(lt_of_not_ge h{i-1}).le'
        if i < len(groups)-1:
            text += f'  by_cases h{i} : t ≤ {lean(endpoints[i][1])}\n'
            text += f'  · exact {g} t ⟨{lower}, h{i}⟩\n'
        else:
            text += f'  exact {g} t ⟨{lower}, ht.2⟩\n'
    return text

def outputs(rows):
    out = {}
    batches=[]
    bounds=[]
    for batch,start in enumerate(range(0,len(rows),10)):
        chunk=rows[start:start+10]
        text=HEADER+'import HodgeProofHP.Stage7ThetaJensenCNVCompactCertificates\n\n'
        text+='/-! Generated by scripts/generate_stage7_cnv_compact_cells.py. -/\n'
        text+='noncomputable section\nnamespace HodgeProofHP\n\n'
        names=[]
        for i,row in enumerate(chunk,start):
            l,u,L,U,a,b,R,_=row
            name=f'hpThetaCNV_compact_cell{i:03d}'
            names.append(name)
            text+='set_option maxRecDepth 4000 in\nset_option maxHeartbeats 4000000 in\n'
            text+=f'-- Exact rational Taylor enclosures and a strict rational box gap.\ntheorem {name} (t : ℝ)\n'
            text+=f'    (ht : t ∈ Set.Icc {lean(l)} {lean(u)}) :\n'
            text+='    0 < hpThetaCNVFarComparisonNumerator t := by\n'
            text+='  exact hpThetaCNV_compact_cell_certificate\n'
            text+=f'    {lean(l)} {lean(u)}\n    {lean(L)} {lean(U)}\n'
            text+=f'    {lean(a)} {lean(b)} {lean(R)} t\n'
            text+='    ht (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)\n'
            text+=f'    ({ARITH})\n    ({UPPER})\n'
            text+='    (by norm_num) (by norm_num) (by norm_num)\n'
            text+=f'    ({ARITH})\n    ({GAP})\n\n'
        batchname=f'hpThetaCNV_compact_cellsBatch{batch:03d}'
        batches.append(batchname)
        bounds.append((chunk[0][0],chunk[-1][1]))
        text+=glue(batchname,names,[(r[0],r[1]) for r in chunk])
        text+=f'\n#print axioms {batchname}\nend HodgeProofHP\n'
        out[f'Stage7ThetaJensenCNVCompactCellsBatch{batch:03d}.lean']=text
    text=HEADER+''.join(f'import HodgeProofHP.Stage7ThetaJensenCNVCompactCellsBatch{i:03d}\n' for i in range(len(batches)))
    text+='\n/-! Complete compact coverage, analytic outer range, and global CNV positivity. -/\n'
    text+='noncomputable section\nnamespace HodgeProofHP\n\n'
    text+=glue('hpThetaCNV_farComparisonNumerator_pos_on_compact',batches,bounds)
    text+='''
theorem hpThetaPhiCNVTailPositive_certified : hpThetaPhiCNVTailPositive := by
  exact hpThetaPhiCNVTailPositive_of_compact_numerator
    hpThetaCNV_farComparisonNumerator_pos_on_compact

theorem hpThetaCNV_weightedTail_comparison_on_far (t : ℝ) (ht : (1 / 50 : ℝ) ≤ t) :
    hpThetaPhiWeightedTail t * |deriv hpRiemannThetaDifferentialKernel t| <
      t * hpRiemannThetaDifferentialKernel t ^ 2 := by
  by_cases houter : 1 ≤ t
  · exact hpThetaCNV_weightedTail_comparison_on_outer t houter
  · exact hpThetaCNV_far_weightedTail_comparison_of_numerator t ht
      (hpThetaCNV_farComparisonNumerator_pos_on_compact t ⟨ht, (lt_of_not_ge houter).le⟩)

#print axioms hpThetaCNV_farComparisonNumerator_pos_on_compact
#print axioms hpThetaPhiCNVTailPositive_certified
#print axioms hpThetaCNV_weightedTail_comparison_on_far
end HodgeProofHP
'''
    out['Stage7ThetaJensenCNVGlobalPositivity.lean']=text
    return out

def main():
    parser=ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir',type=Path,default=Path(__file__).resolve().parents[1]/'HodgeProofHP')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    rows=cells()
    files=outputs(rows)
    if not args.check: args.output_dir.mkdir(parents=True,exist_ok=True)
    for name,content in files.items():
        path=args.output_dir/name
        if args.check:
            assert path.exists() and path.read_text(encoding='utf-8') == content, f'Stale generated source: {path}'
        else:
            path.write_text(content,encoding='utf-8',newline='\n')
    print(f'PASS: {len(rows)} positive rational cells cover [1/50, 1] without gaps')
    print(f'PASS: {len(files)-1} batches and final gluing source '+('match regeneration' if args.check else 'generated'))

if __name__=='__main__': main()
